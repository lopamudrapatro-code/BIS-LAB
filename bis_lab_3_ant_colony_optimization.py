import math
import random


cities = [
    (0, 0),
    (2, 6),
    (5, 3),
    (6, 7),
    (8, 2)
]

number_of_cities = len(cities)


number_of_ants = 10
iterations = 100
alpha = 1
beta = 2
evaporation_rate = 0.5
initial_pheromone = 1
pheromone_amount = 100


distance = [[0] * number_of_cities for _ in range(number_of_cities)]

for i in range(number_of_cities):
    for j in range(number_of_cities):
        distance[i][j] = math.dist(cities[i], cities[j])


pheromone = [
    [initial_pheromone] * number_of_cities
    for _ in range(number_of_cities)
]

best_route = None
best_distance = float("inf")


for _ in range(iterations):
    routes = []

    for _ in range(number_of_ants):
        start = random.randrange(number_of_cities)
        route = [start]


        while len(route) < number_of_cities:
            current_city = route[-1]

            unvisited = [
                city for city in range(number_of_cities)
                if city not in route
            ]

            weights = []
            for city in unvisited:
                trail_strength = pheromone[current_city][city] ** alpha
                closeness = (1 / distance[current_city][city]) ** beta
                weights.append(trail_strength * closeness)

            next_city = random.choices(
                unvisited, weights=weights, k=1
            )[0]
            route.append(next_city)


        route_length = sum(
            distance[route[i]][route[i + 1]]
            for i in range(number_of_cities - 1)
        )
        route_length += distance[route[-1]][route[0]]

        routes.append((route, route_length))

        if route_length < best_distance:
            best_route = route[:]
            best_distance = route_length


    for i in range(number_of_cities):
        for j in range(number_of_cities):
            pheromone[i][j] *= (1 - evaporation_rate)


    for route, route_length in routes:
        deposit = pheromone_amount / route_length

        for i in range(number_of_cities):
            city_a = route[i]
            city_b = route[(i + 1) % number_of_cities]

            pheromone[city_a][city_b] += deposit
            pheromone[city_b][city_a] += deposit


best_route.append(best_route[0])

print("Best route:", best_route)
print("Shortest distance:", best_distance)
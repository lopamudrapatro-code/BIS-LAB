import random


subjects = ["OOM", "CN", "AI", "BIS"]


difficulty = {
    "OOM": 4,
    "CN": 4,
    "AI": 5,
    "BIS": 2
}


urgency = {
    "OOM": 4,
    "CN": 3,
    "AI": 5,
    "BIS": 2
}


slots = ["9-10 AM", "10-11 AM", "2-3 PM", "4-5 PM"]


concentration = [1.0, 0.9, 0.7, 0.5]


POPULATION_SIZE = 30
CROSSOVER_RATE = 0.8
MUTATION_RATE = 0.1
MAX_GENERATIONS = 100
PATIENCE = 20


priority = {
    s: 0.6 * difficulty[s] + 0.4 * urgency[s]
    for s in subjects
}


def create_chromosome():
    chromosome = subjects.copy()
    random.shuffle(chromosome)
    return chromosome

def create_population():
    return [
        create_chromosome()
        for _ in range(POPULATION_SIZE)
    ]


def fitness(chromosome):
    score = 0

    for i, subject in enumerate(chromosome):
        score += priority[subject] * concentration[i]

    return score


def selection(population):
    contestants = random.sample(population, 3)
    winner = max(contestants, key=fitness)
    return winner.copy()


def crossover(parent1, parent2):
    n = len(parent1)
    left, right = sorted(random.sample(range(n), 2))

    def make_child(p1, p2):
        child = [None] * n


        child[left:right + 1] = p1[left:right + 1]


        remaining = [
            gene for gene in p2[right + 1:] + p2[:right + 1]
            if gene not in child
        ]

        positions = (
            list(range(right + 1, n))
            + list(range(0, right + 1))
        )

        for pos, gene in zip(positions, remaining):
            child[pos] = gene

        return child

    return make_child(parent1, parent2), make_child(parent2, parent1)


def mutation(chromosome):
    chromosome = chromosome.copy()

    if random.random() < MUTATION_RATE:
        i, j = random.sample(range(len(chromosome)), 2)
        chromosome[i], chromosome[j] = chromosome[j], chromosome[i]

    return chromosome


def genetic_algorithm():
    population = create_population()

    best = max(population, key=fitness).copy()
    best_score = fitness(best)
    generations_without_improvement = 0

    print("Initial best chromosome:", best)
    print("Initial fitness:", round(best_score, 2))

    for generation in range(1, MAX_GENERATIONS + 1):


        new_population = [best.copy()]

        while len(new_population) < POPULATION_SIZE:
            parent1 = selection(population)
            parent2 = selection(population)


            if random.random() < CROSSOVER_RATE:
                child1, child2 = crossover(parent1, parent2)
            else:
                child1 = parent1.copy()
                child2 = parent2.copy()


            new_population.append(mutation(child1))

            if len(new_population) < POPULATION_SIZE:
                new_population.append(mutation(child2))

        population = new_population

        generation_best = max(population, key=fitness)
        generation_score = fitness(generation_best)

        if generation_score > best_score:
            best = generation_best.copy()
            best_score = generation_score
            generations_without_improvement = 0
        else:
            generations_without_improvement += 1

        if generation % 10 == 0:
            print(
                f"Generation {generation}: "
                f"Best fitness = {best_score:.2f}"
            )


        if generations_without_improvement >= PATIENCE:
            print("Terminated: no improvement for 20 generations.")
            break


    print("\nOPTIMIZED STUDY TIMETABLE")
    print("-" * 42)

    for i, subject in enumerate(best):
        print(
            f"{slots[i]:10} -> {subject:4} "
            f"(Priority: {priority[subject]:.1f})"
        )

    print("-" * 42)
    print("Best fitness score:", round(best_score, 2))
    print("All subjects scheduled:", set(best) == set(subjects))

    return best


random.seed(42)
best_timetable = genetic_algorithm()